pub fn param_print(p: usize) {
    if p >= 1_000_000_000 {
        println!("{:.1}B", p as f64 / 1_000_000_000.0);
    } else if p >= 1_000_000 {
        println!("{:.1}M", p as f64 / 1_000_000.0);
    } else if p >= 1_000 {
        println!("{:.1}K", p as f64 / 1_000.0);
    } else {
        println!("{}", p);
    }
}

